-- ⚠ TROIS GARDE-FOUS, et ils comptent plus que l'envoi lui-même :
--   ① UNE FOIS PAR SEMAINE PAR ASSOCIATION, pas une fois par jour. Un rappel qui
--      arrive tous les matins finit dans la corbeille sans être lu — et le jour où
--      il compte vraiment, il y va aussi.
--   ② SANS CLÉ, ÇA NE PLANTE PAS : la fonction rend -1 et ne fait rien. La tâche
--      peut donc être posée AVANT que le compte d'envoi existe.
--   ③ TOUT ENVOI EST JOURNALISÉ (`rappels_asso`). Sans journal, impossible de savoir
--      si un rappel n'est pas parti ou s'il est parti et n'a pas été lu.
--
-- ⚠ LES ACCENTS PASSENT EN BASE64 : le presse-papier vers l'éditeur SQL les abîme
