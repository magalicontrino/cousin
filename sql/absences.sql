create table if not exists public.absences (
  id            bigint generated by default as identity primary key,
  nom           text        not null check (char_length(nom) between 1 and 80),
  lam           boolean     not null default false,
  statut        text        not null default 'nonjust'
                            check (statut in ('nonjust','just','hospit')),
  nuits         date[]      not null default '{}',
  rentre_le     timestamptz, rentre_par     text,
  desencode_le  timestamptz, desencode_par  text,
  ajoute_par    text,
  uid           uuid        not null default auth.uid(),
  cree_le       timestamptz not null default now()
);

alter table public.absences enable row level security;

drop policy if exists abs_lecture on public.absences;
create policy abs_lecture on public.absences for select to authenticated
  using (public.peut_voir_entrants());

drop policy if exists abs_ajout on public.absences;
create policy abs_ajout on public.absences for insert to authenticated
  with check (public.peut_voir_entrants() and uid = auth.uid());

drop policy if exists abs_maj on public.absences;
create policy abs_maj on public.absences for update to authenticated
  using (public.peut_voir_entrants()) with check (public.peut_voir_entrants());

-- Retirer : tout le groupe A, B, C (Mag, 03/10/2026 : pas de "Rentre" ni de
-- "Desencode", "il faut juste pouvoir les retirer" -- une corbeille).
drop policy if exists abs_retirer on public.absences;
create policy abs_retirer on public.absences for delete to authenticated
  using (public.peut_voir_entrants());

