-- ═══ AIDES-SOIGNANTES (Mag, 13/10/2026 : « c'est bien, on testera, je vais leur demander ») ═══
-- Deux listes : les SOINS DU JOUR (douche, toilette) et LES PLUS FRAGILES (un passage le matin).
-- « Quand quelqu'un ajoute ou retire une personne, il faut mettre le nom : retirer une personne fragile,
-- c'est grave. » → cree_par / retire_par / retire_le ; une personne retirée n'est pas effacée.
create table if not exists public.aides_personnes (
  id          bigint generated by default as identity primary key,
  liste       text        not null,                      -- 'soins' | 'fragiles'
  chambre     text,
  nom         text        not null,
  soins       jsonb       not null default '[]'::jsonb,  -- ["douche","toilette"]
  note        text,                                      -- la petite note signée (infirmiers…)
  note_par    text,
  note_le     timestamptz,
  cree_le     timestamptz not null default now(),
  cree_par    text,
  retire_le   timestamptz,
  retire_par  text
);
-- Ce qui est fait chaque jour : un soin fait, un passage du matin (va bien / à signaler).
create table if not exists public.aides_jour (
  id           bigint generated by default as identity primary key,
  personne_id  bigint      not null references public.aides_personnes(id) on delete cascade,
  jour         date        not null,
  quoi         text        not null,                     -- 'soin' | 'matin'
  etat         text        not null,                     -- 'fait' | 'va_bien' | 'signaler'
  mot          text,
  par          text,
  le           timestamptz not null default now(),
  unique (personne_id, jour, quoi)
);
create index if not exists aides_jour_jour_idx on public.aides_jour (jour);
alter table public.aides_personnes enable row level security;
alter table public.aides_jour enable row level security;
drop policy if exists ap_tout on public.aides_personnes;
create policy ap_tout on public.aides_personnes for all to authenticated using (true) with check (true);
drop policy if exists aj_tout on public.aides_jour;
create policy aj_tout on public.aides_jour for all to authenticated using (true) with check (true);
grant select, insert, update, delete on public.aides_personnes to authenticated;
grant select, insert, update, delete on public.aides_jour to authenticated;
