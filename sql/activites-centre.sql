-- ═══ LES ACTIVITÉS DU CENTRE (Mag, 13/10/2026) ═══ N'importe qui pose une activité (date, heure, lieu) ; après coup,
-- un mot « comment ça s'est passé ». Pas un programme à remplir : rien n'est obligatoire.
create table if not exists public.activites_centre (
  id        bigint generated by default as identity primary key,
  titre     text        not null,
  jour      date        not null,
  heure     text,
  lieu      text,
  par       text,
  par_uid   uuid,
  cree_le   timestamptz not null default now(),
  cr        text,
  cr_par    text,
  cr_le     timestamptz
);
create index if not exists activites_centre_jour_idx on public.activites_centre (jour);
alter table public.activites_centre enable row level security;
drop policy if exists ac_tout on public.activites_centre;
create policy ac_tout on public.activites_centre for all to authenticated using (true) with check (true);
grant select, insert, update, delete on public.activites_centre to authenticated;
