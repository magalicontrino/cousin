-- ═══ LE RAPPORT DU JOUR (Mag, 13/10/2026) ═══ Les petits messages écrits à la main : info importante, entrée sans
-- condition, technique, à toutes les équipes. Chacun signé ; visible jusqu'à « jusqu_au ». Pas pour le groupe D (app).
create table if not exists public.rapport_messages (
  id        bigint generated by default as identity primary key,
  rubrique  text        not null,
  texte     text        not null,
  chambre   text,
  par       text,
  par_uid   uuid,
  cree_le   timestamptz not null default now(),
  jusqu_au  date        not null
);
alter table public.rapport_messages enable row level security;
drop policy if exists rm_tout on public.rapport_messages;
create policy rm_tout on public.rapport_messages for all to authenticated using (true) with check (true);
grant select, insert, update, delete on public.rapport_messages to authenticated;
