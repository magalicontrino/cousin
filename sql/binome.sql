-- ═══ LES RÉPONSES SOUS UNE LIGNE (Mag, 07/10/2026) ═══
-- « Une réponse sous la ligne, et je veux une notification aussi. »
-- Table à part, et pas une colonne de la ligne : à deux qui répondent en même temps,
-- une colonne réécrite en bloc perdrait une des deux réponses.
create table if not exists public.binome_reponses (
  id       bigint generated by default as identity primary key,
  ligne_id bigint      not null references public.binome_lignes(id) on delete cascade,
  binome   text        not null,
  texte    text        not null,
  par      text,
  uid      uuid        not null default auth.uid(),
  cree_le  timestamptz not null default now()
);
create index if not exists binome_reponses_idx on public.binome_reponses (ligne_id);
alter table public.binome_reponses enable row level security;
drop policy if exists br_tout on public.binome_reponses;
create policy br_tout on public.binome_reponses for all to authenticated
  using (public.est_du_binome(binome)) with check (public.est_du_binome(binome));
grant select, insert, update, delete on public.binome_reponses to authenticated;
