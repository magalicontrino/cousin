-- 13/10/2026 : le journal de l'app (Mag : « je veux un rapport de tout ce qui s'est fait, qui a retire quoi, ce qui
-- est utilise, ou c'est abandonne »). Tout le monde ECRIT ses propres lignes ; seule l'ADMIN les LIT.
-- (Pas d'accents dans ce fichier : l'editeur SQL les abime.)
create table if not exists public.journal (
  id       bigint generated by default as identity primary key,
  le       timestamptz not null default now(),
  qui      text,
  qui_uid  uuid,
  action   text not null,
  objet    text,
  detail   text
);
create index if not exists journal_le_idx on public.journal (le);
create or replace function public.est_admin_journal()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.allowed_emails a
    where lower(a.email) = lower(auth.jwt() ->> 'email') and coalesce(a.actif, true) and coalesce(a.admin, false));
$$;
grant execute on function public.est_admin_journal() to authenticated;
alter table public.journal enable row level security;
drop policy if exists j_ecrit on public.journal;
create policy j_ecrit on public.journal for insert to authenticated with check (qui_uid = auth.uid());
drop policy if exists j_lit on public.journal;
create policy j_lit on public.journal for select to authenticated using (public.est_admin_journal());
grant select, insert on public.journal to authenticated;
