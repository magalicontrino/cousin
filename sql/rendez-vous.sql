create policy rdv_ecriture on public.rendez_vous for insert to authenticated with check (public.peut_ecrire_rdv());
drop policy if exists rdv_maj on public.rendez_vous;
create policy rdv_maj on public.rendez_vous for update to authenticated using (public.peut_ecrire_rdv()) with check (public.peut_ecrire_rdv());
drop policy if exists rdv_suppr on public.rendez_vous;
create policy rdv_suppr on public.rendez_vous for delete to authenticated using (public.peut_ecrire_rdv());
grant select, insert, update, delete on public.rendez_vous to authenticated;
